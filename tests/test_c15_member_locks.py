# --- Conda locks: explicit files, md5 resolved to sha256 by an exact solve ---


def _explicit(*lines):
    return "# platform: linux-64\n@EXPLICIT\n" + "".join(line + "\n" for line in lines)


def test_explicit_lines_with_md5_or_sha256_are_read(tmp_path):
    policy = _policy(tmp_path)
    entries = parse_explicit(_explicit(f"{BASE}samtools-1.21-h_0.conda#{MD5}",
                                       f"{BASE}_openmp_mutex-4.5-20_gnu.tar.bz2#sha256:{A}",
                                       f"https://conda.anaconda.org/conda-forge/noarch/tzdata-2024a-h_1.conda#{B}"),
                             policy)
    assert [(item.name, item.version, item.build, item.md5, item.sha256) for item in entries] == [
        ("_openmp_mutex", "4.5", "20_gnu", None, A), ("samtools", "1.21", "h_0", MD5, None),
        ("tzdata", "2024a", "h_1", None, B)]


@pytest.mark.parametrize("text", [
    f"{BASE}samtools-1.21-h_0.conda#{MD5}\n",                                         # no header
    _explicit(f"{BASE}samtools-1.21-h_0.conda"),                                       # no hash
    _explicit(f"https://conda.anaconda.org/defaults/linux-64/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"https://conda.anaconda.org/conda-forge/osx-64/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"https://conda.anaconda.org/conda-forge/linux-64/../x/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"http://conda.anaconda.org/conda-forge/linux-64/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"https://evil.example/conda-forge/linux-64/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"file:///tmp/samtools-1.21-h_0.conda#{MD5}"),
    _explicit(f"{BASE}samtools-1.21.conda#{MD5}"),                                     # not name-version-build
    _explicit(f"{BASE}samtools-1.21-h_0.conda#{MD5}", f"{BASE}samtools-1.20-h_0.conda#{MD5}"),
    _explicit(f"{BASE}samtools-1.21-h_0.conda#{'2' * 40}"),                            # neither md5 nor sha256
    "@EXPLICIT\n",
])
def test_explicit_files_outside_the_allowed_channels_or_malformed_are_refused(tmp_path, text):
    with pytest.raises(CondaError) as raised:
        parse_explicit(text, _policy(tmp_path))
    assert raised.value.code == "CONDA_LOCK_FILE_INVALID"


def _solution(*items):
    return {"success": True, "actions": {"LINK": [
        {"name": name, "version": version, "build_string": "h_0", "url": f"{BASE}{name}-{version}-h_0.conda",
         "md5": md5, "sha256": sha} for name, version, md5, sha in items]}}


@pytest.mark.parametrize("solution, code", [
    (_solution(("samtools", "1.21", MD5, A), ("htslib", "1.21", MD5, B)), None),
    (_solution(("samtools", "1.21", "2" * 32, A), ("htslib", "1.21", MD5, B)), "CONDA_LOCK_MISMATCH"),
    (_solution(("samtools", "1.21", MD5, A), ("htslib", "1.21", MD5, C)), "CONDA_LOCK_MISMATCH"),
    (_solution(("samtools", "1.21", MD5, A), ("htslib", "1.21", MD5, B), ("zlib", "1.3", MD5, C)),
     "CONDA_LOCK_MISMATCH"),  # The lock was incomplete: the solver needed another package.
])
def test_an_exact_solve_turns_md5_into_sha256_or_refuses_the_lock(tmp_path, monkeypatch, solution, code):
    policy = _policy(tmp_path)
    solved = []
    monkeypatch.setattr(conda_module, "_solve_payload", lambda policy, specs, work: solved.append(specs) or solution)
    entries = parse_explicit(_explicit(f"{BASE}samtools-1.21-h_0.conda#{MD5}", f"{BASE}htslib-1.21-h_0.conda#{B}"),
                             policy)
    if code is None:
        locked = lock_explicit(policy, entries, tmp_path)
        assert [(item.name, item.sha256) for item in locked] == [("htslib", B), ("samtools", A)]
    else:
        with pytest.raises(CondaError) as raised:
            lock_explicit(policy, entries, tmp_path)
        assert raised.value.code == code
    assert solved == [("htslib==1.21=h_0", "samtools==1.21=h_0")]  # Exact builds only.


