# --- Wheel locks: exactly pinned and hashed ---


def test_a_pip_compile_lock_is_read_with_continuations_comments_and_several_hashes():
    text = (f"# This file is autogenerated by pip-compile\nSix==1.16.0 \\\n    --hash=sha256:{A} \\\n"
            f"    --hash=sha256:{B}\n    # via example\nPyYAML==6.0.2 --hash=sha256:{C}  # pinned\n")
    pins = parse_wheel_lock(text)
    assert pins == (PinnedWheel("pyyaml", "6.0.2", frozenset({C})), PinnedWheel("six", "1.16.0", frozenset({A, B})))
    assert render_pins(pins) == f"pyyaml==6.0.2 --hash=sha256:{C}\nsix==1.16.0 --hash=sha256:{A} --hash=sha256:{B}\n"


@pytest.mark.parametrize("line", [
    "six==1.16.0",                                       # no hash
    f"six>=1.16 --hash=sha256:{A}",                       # not exact
    f"six[extra]==1.16.0 --hash=sha256:{A}",              # extras
    f"six==1.16.0 ; python_version < '3.12' --hash=sha256:{A}",  # marker
    f"six==1.16.0 --hash=md5:{MD5}",                      # not sha256
    f"--index-url https://evil.example/simple\nsix==1.16.0 --hash=sha256:{A}",
    f"six @ https://evil.example/six.whl --hash=sha256:{A}",
    f"-r other.txt\nsix==1.16.0 --hash=sha256:{A}",
    f"six==1.16.0 --hash=sha256:{A}\nSIX==1.16.0 --hash=sha256:{B}",  # twice
    f"six==1.16.0 --hash=sha256:{A} --no-deps",
    "# only a comment\n",
])
def test_anything_but_exact_hashed_pins_is_refused(line):
    with pytest.raises(WheelLockError):
        parse_wheel_lock(line + "\n")


