# --- Admission of a lock-built image ---


BASE_SOURCE = SourceIdentity(kind=SourceKind.OCI_MANIFEST, digest="sha256:" + "e" * 64, platform="linux/amd64")
LOCKED = ({"name": "six", "version": "1.16.0", "sha256": A},)


def _base():
    return ApprovedImage(key="lab-python", reference="sha256:" + "f" * 64, source=BASE_SOURCE,
                         entry_points={ExecutionRuntime.PYTHON: ("python",), ExecutionRuntime.SHELL: ("sh",)})


def _built(**changes):
    values = dict(reference="sha256:" + "9" * 64, produced_by="a" * 32, locked=LOCKED,
                  recipe="python-wheels-v1", machine="x86_64", size_bytes=1000)
    return LockedBuild(**{**values, **changes})


def _runtime_probe(image, runtime):
    return _probe(python={"six": "1.16.0"}) if runtime is ExecutionRuntime.PYTHON else b"x86_64\n"


def _lock_admission(tmp_path, *, quota=10**9, probe=None, keys=()):
    store = CatalogStore(tmp_path / "personal").initialize()
    realizer = FakeRealizer()
    admission = ImageAdmission(
        store=store, scope=ImageScope.PERSONAL, owner_user_id="member", admitted_by="member", realizer=realizer,
        probe=probe or _runtime_probe, machine="x86_64",
        limits=AdmissionLimits(max_image_bytes=10**6, quota_bytes=quota), staging_root=tmp_path / "staging",
        registry_client=lambda: pytest.fail("a lock build pulls nothing"),
        existing_keys=lambda: set(keys) | set(store.records()))
    return admission, store, realizer


def test_a_lock_built_image_is_personal_derived_and_keeps_the_base_runtimes(tmp_path):
    admission, store, _ = _lock_admission(tmp_path)
    probed = []
    admission.probe = lambda image, runtime: probed.append(runtime) or _runtime_probe(image, runtime)

    record = admission.admit_locked(key="six-tools", purpose="Six on Python.", gpu=GpuSupport.NONE,
                                    base=_base(), build=lambda base: _built())

    assert record.source.kind is SourceKind.DERIVED and record.scope is ImageScope.PERSONAL
    assert set(record.entry_points) == {ExecutionRuntime.PYTHON, ExecutionRuntime.SHELL}
    assert sorted(probed) == sorted(record.entry_points)  # Every inherited entry point is probed.
    assert record.realizations[0].produced_by == "lock:" + "a" * 32
    assert store.records()["six-tools"] == record


